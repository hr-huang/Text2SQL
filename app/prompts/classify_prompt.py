CLASSIFY_SYSTEM_PROMPT = """
你判断用户的数据查询问题是「简单」还是「复杂」。

简单（simple）：
  - 一句 SELECT + JOIN + GROUP BY + ORDER BY 就能回答
  - 只有一个统计目标（单个 COUNT/SUM/AVG）
  - 例如："一共有多少位艺术家？""每个国家的客户数量？""2010年每个月的销售额？"

复杂（complex）——只有「多跳查询」才算，即必须先拿到中间结果、再用中间结果查下一步：
  - 需要先筛出一个集合，再基于这个集合做第二次统计
    例如："消费最高的10个客户分别买了哪些品类？" → 先算Top10客户，再查他们买过什么
  - 多个互相独立的统计目标，必须分别查询后再合并
    例如："每月新增客户数和订单量？" → 两个不同表、不同口径的指标，无法一条 SQL 同时聚合
  - 需要先算出阈值/排名/分组，再拿这个结果去过滤另一批数据
    例如："退货率最高的3个品类，它们的供应商有哪些？"

简单（simple）——以下都**不算**复杂，因为一条 SQL 就能写完：
  - 含子查询、窗口函数、CTE、自连接的查询
  - "高于平均值""排名前X""比XX多"这类——用子查询或窗口函数一步可解
    例如："比平均消费额高的客户住在哪些城市？" → 子查询即可，是简单
    例如："价格高于品类均价的商品有哪些？" → 窗口函数即可，是简单

判断口诀：**能否用一条 SQL（哪怕很复杂、带子查询/CTE）写出来？能 → simple；不能，必须分两步拿到中间结果 → complex。**

如果用户问题完全不涉及数据查询（闲聊、问候等），返回 not_data。

输出 JSON：
{
  "complexity": "simple" | "complex" | "not_data",
  "reason": "一句话说明判断理由"
}
"""


def build_classify_user_prompt(question: str) -> str:
    return f"问题：{question}"
